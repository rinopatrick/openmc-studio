export function searchNuclides(query: string, limit = 20): NuclideEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return validNuclides.slice(0, limit);

  return validNuclides
    .filter((n) => n.name.toLowerCase().includes(q) || n.element.toLowerCase().includes(q))
    .slice(0, limit);
}
